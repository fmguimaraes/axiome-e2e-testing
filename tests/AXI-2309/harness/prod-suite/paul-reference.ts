import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { FIXTURES_DIR, PROD_SUITE_FIXTURES } from './fixtures';

/**
 * AXI-2319 (epic AXI-2309, FR31/AC12, SI-042 + SI-053) — the EXPECTED VALUES
 * of Paul Dalmas's methods, loaded from two committed files and nothing else:
 *
 * - `paul-probes.json` — the one declaration of every probe (the run the
 *   platform executes + the fields checked, with Paul's slide target when the
 *   slide prints one). Targets are copied from the AXI-2066 reproduction
 *   (`axiome-docs/demo/mag4-microbiote/data/targets.json`, sha256 recorded in
 *   the file).
 * - `paul-r-reference.json` — the INDEPENDENT R computation of every checked
 *   field on the same fixture bytes, generated by `paul-r-reference.R`
 *   through `scripts/prod-suite-r-reference.ts` in the pinned R image, and
 *   stamped with the sha256 of the probes file, the R script and both
 *   fixtures. {@link assertReferenceFresh} refuses a stale reference: a probe
 *   or fixture edited without regenerating R would otherwise compare the
 *   platform against numbers computed for a different question.
 */

export const PAUL_REFERENCE_DIR = path.join(FIXTURES_DIR, 'paul-reference');
export const PAUL_PROBES_FILE = 'paul-probes.json';
export const PAUL_R_SCRIPT_FILE = 'paul-r-reference.R';
export const PAUL_R_REFERENCE_FILE = 'paul-r-reference.json';

export interface ProbeFilter {
  column: string;
  operator: 'in' | 'eq';
  value: string | string[];
}

export interface PaulCheck {
  /** Selects the ONE result row the check reads (empty/absent = the single row). */
  row?: Record<string, string>;
  field: string;
  /** Paul's printed number (its decimals = the precision checked) or `ns` (p > 0.05). */
  target?: string;
  targetKey?: string;
}

export interface PaulProbe {
  id: string;
  operationId: string;
  fixture: string;
  filters: ProbeFilter[];
  roleBindings: Record<string, string | string[]>;
  pivot?: Record<string, unknown>;
  operationParams: Record<string, unknown>;
  rowKey: string[];
  checks: PaulCheck[];
}

export interface RReferenceRow {
  row: Record<string, string>;
  values: Record<string, number>;
}

export interface RReferenceProbe {
  id: string;
  operationId: string;
  n: number;
  rows: RReferenceRow[];
}

export interface RReference {
  generator: {
    image: string;
    rVersion: string;
    packages: Record<string, string>;
    probesSha256: string;
    scriptSha256: string;
    fixtureSha256: Record<string, string>;
  };
  probes: RReferenceProbe[];
}

export interface PaulReference {
  probes: PaulProbe[];
  r: RReference;
}

export const sha256Hex = (bytes: Buffer | string) => createHash('sha256').update(bytes).digest('hex');

function readJson(file: string): any {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** The hashes the reference must have been generated from (the committed bytes, now). */
export function currentInputHashes(dir = PAUL_REFERENCE_DIR, fixturesDir = FIXTURES_DIR) {
  return {
    probesSha256: sha256Hex(readFileSync(path.join(dir, PAUL_PROBES_FILE))),
    scriptSha256: sha256Hex(readFileSync(path.join(dir, PAUL_R_SCRIPT_FILE))),
    fixtureSha256: Object.fromEntries(
      PROD_SUITE_FIXTURES.map((f) => [f.key, sha256Hex(readFileSync(path.join(fixturesDir, f.file)))]),
    ) as Record<string, string>,
  };
}

/** Refuse a reference generated from other probes, another R script or other fixture bytes. */
export function assertReferenceFresh(r: RReference, current: ReturnType<typeof currentInputHashes>): void {
  const stale: string[] = [];
  if (r.generator?.probesSha256 !== current.probesSha256) stale.push(PAUL_PROBES_FILE);
  if (r.generator?.scriptSha256 !== current.scriptSha256) stale.push(PAUL_R_SCRIPT_FILE);
  for (const [key, hash] of Object.entries(current.fixtureSha256)) {
    if (r.generator?.fixtureSha256?.[key] !== hash) stale.push(`fixture ${key}`);
  }
  if (stale.length > 0) {
    throw new Error(`${PAUL_R_REFERENCE_FILE} is stale (${stale.join(', ')} changed) — regenerate it: npx tsx scripts/prod-suite-r-reference.ts`);
  }
}

/** Every probe must have an R entry, and every checked row must exist in it exactly once. */
export function assertReferenceCovers(probes: PaulProbe[], r: RReference): void {
  for (const probe of probes) {
    const ref = r.probes.find((p) => p.id === probe.id);
    if (!ref) throw new Error(`R reference has no entry for probe ${probe.id}`);
    for (const check of probe.checks) {
      const hits = ref.rows.filter((row) => rowMatches(row.row, check.row));
      if (hits.length !== 1 || typeof hits[0].values[check.field] !== 'number') {
        throw new Error(`R reference for ${probe.id} has no single value for ${describeCheck(check)}`);
      }
    }
  }
}

/** Load, verify fresh, verify complete — the only way the executor gets its expected values. */
export function loadPaulReference(dir = PAUL_REFERENCE_DIR, fixturesDir = FIXTURES_DIR): PaulReference {
  const probes: PaulProbe[] = readJson(path.join(dir, PAUL_PROBES_FILE)).probes;
  const r: RReference = readJson(path.join(dir, PAUL_R_REFERENCE_FILE));
  assertReferenceFresh(r, currentInputHashes(dir, fixturesDir));
  assertReferenceCovers(probes, r);
  return { probes, r };
}

/** True when `row` carries every key/value of `selector` (string comparison). */
export function rowMatches(row: Record<string, unknown> | null | undefined, selector?: Record<string, string>): boolean {
  if (!selector) return true;
  return Object.entries(selector).every(([k, v]) => row != null && String(row[k]) === v);
}

export function describeCheck(check: PaulCheck): string {
  const sel = check.row ? Object.values(check.row).join(' vs ') : '';
  return sel ? `${check.field}[${sel}]` : check.field;
}
